/**
 * 小时聚合的桶计算（M5 / B2–B4）。
 *
 * ── 为什么单独成一个文件 ────────────────────────────────────────────────
 * 桶的截断规则有**两个使用方**，必须逐位一致：
 *   · Worker（归并时算当前事件属于哪个桶）
 *   · 回填脚本 scripts/stats-backfill.cjs（从明细重建历史桶）
 * 差一毫秒就会把同一条明细算进两个桶，对账立刻发现
 * `sum(event_count) ≠ 明细条数`。放在这里让两边 import 同一个函数，
 * 而不是各自写一遍 Math.floor。
 *
 * ── 为什么按 UTC 而不是本地时区 ────────────────────────────────────────
 * 服务器时区是可变的（容器镜像、TZ 环境变量、夏令时）。按本地时区截断的话，
 * 换台机器重跑回填就会得出不同的桶值 —— 那是"同一份明细算出两套趋势"的经典事故。
 * UTC 是唯一不依赖运行环境的基准。
 * 展示层要"北京时间的小时"时，应该在**读取侧**加 8 小时偏移，不要在这里改。
 *
 * ── 也不要用 SQL 的 date_trunc ─────────────────────────────────────────
 * `date_trunc('hour', timestamptz)` 按**会话时区**截断。同一个值在不同 TimeZone
 * 下会落进不同的桶。回填脚本用的是数学等价的
 * `to_timestamp(floor(extract(epoch from ts) / 3600) * 3600)`，与本函数逐位相符。
 */

/** 一小时的毫秒数 */
const HOUR_MS = 60 * 60 * 1000;

/**
 * 把时间戳截断到 **UTC 整点**。
 *
 * 用 epoch 毫秒整除，而不是 `setMinutes(0, 0, 0)` —— 后者按本地时区截断。
 * `Math.floor` 对负值（1970 之前）也正确向下取整。
 *
 * @example
 *   toHourBucket(new Date('2026-10-22T09:37:41.512Z'))
 *   // → 2026-10-22T09:00:00.000Z
 */
export function toHourBucket(when: Date): Date {
  return new Date(Math.floor(when.getTime() / HOUR_MS) * HOUR_MS);
}
